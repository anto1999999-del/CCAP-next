/**
 * Build the 301 map from the old blog subdomain to the new /blog paths.
 *
 * Usage:  node scripts/build-redirect-map.mjs
 *
 * Generated from the export rather than written by hand, so it is derived from
 * the URLs WordPress actually published — every post carries the canonical
 * Yoast served, and that is what is redirected.
 *
 * This map is the single most consequential artefact of the blog migration. The
 * site has 233 referring domains and at least one article ranking around
 * position 11; a 301 keeps that, a missing entry throws it away. Every old URL
 * has to appear here, and the subdomain has to keep resolving indefinitely —
 * not for a token few months.
 *
 * Output is an Apache/LiteSpeed rewrite block, because the redirects belong on
 * the `blog.` vhost. Handling them in the app would mean every old link still
 * reaching the Node process just to be told to go elsewhere.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const NEW_ORIGIN = "https://centralcoastautoparts.com.au";
const OLD_HOST = "blog.centralcoastautoparts.com.au";

const CONTENT = path.join(process.cwd(), "content", "blog");
const OUT = path.join(process.cwd(), "content", "redirects");

/** Old path -> new path. */
function mapping(posts, taxonomies) {
  const rows = [];

  for (const post of posts) {
    // Prefer the canonical Yoast published; fall back to the slug.
    let oldPath = `/${post.slug}/`;
    if (post.seo?.legacyCanonical) {
      try {
        oldPath = new URL(post.seo.legacyCanonical).pathname;
      } catch {
        /* keep the slug-derived path */
      }
    }
    // Vehicles were posts in a "Gallery" category on WordPress. On the new
    // site they are a gallery of their own, so they redirect there instead.
    const isVehicle = post.categorySlug === "gallery";
    rows.push({
      from: oldPath,
      to: isVehicle ? `/gallery/${post.slug}` : `/blog/${post.slug}`,
      kind: isVehicle ? "vehicle" : "post",
    });
  }

  for (const category of taxonomies.categories) {
    rows.push({
      from: `/category/${category.slug}/`,
      to: category.slug === "gallery" ? `/gallery` : `/blog`,
      kind: "category",
    });
  }

  for (const tag of taxonomies.tags) {
    rows.push({ from: `/tag/${tag.slug}/`, to: `/blog`, kind: "tag" });
  }

  // The blog home, its feed, and the media library.
  rows.push({ from: "/", to: "/blog", kind: "home" });
  rows.push({ from: "/feed/", to: "/blog", kind: "feed" });

  return rows;
}

function toApacheConfig(rows) {
  const lines = [
    "# Redirects from the retired WordPress blog to the Next.js site.",
    "#",
    "# Generated by scripts/build-redirect-map.mjs — do not hand-edit; re-run it.",
    "#",
    "# This belongs on the blog.centralcoastautoparts.com.au vhost. The subdomain",
    "# must keep resolving and keep its TLS certificate indefinitely: these",
    "# redirects are load-bearing for search rankings and for the 233 domains",
    "# that link here, not a temporary courtesy.",
    "",
    "<IfModule mod_rewrite.c>",
    "  RewriteEngine On",
    "",
    "  # Uploads keep their path, so old image URLs still resolve.",
    `  RewriteRule ^wp-content/uploads/(.*)$ ${NEW_ORIGIN}/blog-media/$1 [R=301,L]`,
    "",
  ];

  for (const row of rows) {
    const pattern = row.from === "/" ? "^$" : `^${row.from.replace(/^\/|\/$/g, "")}/?$`;
    lines.push(`  RewriteRule ${pattern} ${NEW_ORIGIN}${row.to} [R=301,L]`);
  }

  lines.push(
    "",
    "  # Anything else on the old blog goes to the new index rather than 404ing,",
    "  # since every real URL is listed above.",
    `  RewriteRule ^(.*)$ ${NEW_ORIGIN}/blog [R=301,L]`,
    "</IfModule>",
    "",
  );

  return lines.join("\n");
}

async function main() {
  const posts = JSON.parse(
    await readFile(path.join(CONTENT, "posts.json"), "utf8"),
  );
  const taxonomies = JSON.parse(
    await readFile(path.join(CONTENT, "taxonomies.json"), "utf8"),
  );

  const rows = mapping(posts, taxonomies);
  await mkdir(OUT, { recursive: true });

  await writeFile(
    path.join(OUT, "blog-redirects.json"),
    JSON.stringify({ oldHost: OLD_HOST, newOrigin: NEW_ORIGIN, rows }, null, 2),
    "utf8",
  );
  await writeFile(
    path.join(OUT, "blog-redirects.conf"),
    toApacheConfig(rows),
    "utf8",
  );

  const byKind = rows.reduce((acc, row) => {
    acc[row.kind] = (acc[row.kind] ?? 0) + 1;
    return acc;
  }, {});

  console.log(`Wrote ${rows.length} redirects to content/redirects/`);
  for (const [kind, count] of Object.entries(byKind)) {
    console.log(`  ${kind.padEnd(10)} ${count}`);
  }

  const duplicates = rows
    .map((r) => r.from)
    .filter((from, i, all) => all.indexOf(from) !== i);
  if (duplicates.length) {
    console.warn(`\n  WARNING duplicate source paths: ${duplicates.join(", ")}`);
  }
}

main().catch((error) => {
  console.error("Failed:", error.message);
  process.exitCode = 1;
});
